package com.basirize;

import java.util.List;

// ============================================================
// 問題タイプ（ProblemType）
// ============================================================
// 「小1のたし算・ひき算」のような、画面に1枚のカードとして出る単位。
//
// 生成器（アルゴリズム）と、それを説明する情報を組み合わせて1つにする。
//
// ------------------------------------------------------------
// なぜ生成器に id やタイトルを持たせないのか
// ------------------------------------------------------------
// 1つの生成器が複数の問題タイプを担うため。
//
//   FactoringGenerator ─┬─ 中3 因数分解      （範囲9）
//                       └─ 高1 因数分解（発展）（範囲15）
//
//   ArithmeticGenerator ─── 設定違いで小1〜中1の8タイプ
//
// 生成器側に持たせると、この1対多が表現できない。
//
// ------------------------------------------------------------
// generate() が1行だけの理由
// ------------------------------------------------------------
// 自分では何も計算していない。generator にそのまま渡しているだけ。
// 呼ぶ側が type.generator().generate(10) と2段書かずに済むようにしている。
// ============================================================
public record ProblemType(
        String id,
        String level,
        String grade,
        String title,
        ProblemGenerator generator) {

    public List<Problem> generate(int count) {
        return generator.generate(count);
    }
}
