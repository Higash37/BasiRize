package com.basirize;

// ============================================================
// 問題（Problem）
// ============================================================
// 問題文と答えをセットで持つ箱。
//
//   question  "(3 + 5) × 2 = ?"
//   answer    "16"
//
// ------------------------------------------------------------
// なぜ1つの型にまとめるのか
// ------------------------------------------------------------
// 問題文のリストと答えのリストを別々に持つと、片方だけ並べ替えたり
// 差し替えたりしたときに対応がズレる。しかもズレても気づけない。
// 常にセットで扱えば、そもそもズレようがない。
//
// ------------------------------------------------------------
// なぜ answer が String なのか
// ------------------------------------------------------------
// 四則演算だけなら int で足りる。
// しかし今後こういう答えが出てくる。
//
//   一次方程式    x = 3
//   連立方程式    x = 2, y = -1
//   因数分解      (x + 3)(x - 5)
//   平方根        3√2
//
// どれも数値では表せないので、最初から String にしておく。
// フロントエンドの TypeScript 版も answer: string になっている。
//
// ------------------------------------------------------------
// Problem は自分の作り方を知らない
// ------------------------------------------------------------
// ランダムに問題を作るのは ArithmeticGenerator の責務。
// この箱は値を持つだけなので、因数分解などの別の生成ロジックからも
// そのまま使い回せる。
// ============================================================
public record Problem(String question, String answer) {
}
