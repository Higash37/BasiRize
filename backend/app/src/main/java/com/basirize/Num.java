package com.basirize;

// ============================================================
// 数（Num）
// ============================================================
// 木の葉っぱ。数を1つ持つだけの式。
//
//       ×
//      / \
//     +   2      ← この 2 が Num
//    / \
//   3   5        ← この 3 と 5 も Num
//
// ------------------------------------------------------------
// なぜ int をそのまま使わないのか
// ------------------------------------------------------------
// Calculation の左右に入れられるのは Expression だけ。
// int は Java 組み込みの型なので、こちらから implements を付けられない。
//
//   new Calculation(3, Operator.ADD, new Num(7))          ← 通らない
//   new Calculation(new Num(3), Operator.ADD, new Num(7)) ← 通る
//
// int を Expression として扱えるようにする包みが、この Num。
//
// また、Calculation の左に int を入れられる形にしてしまうと、
// そこに Calculation を入れられなくなり、木が作れなくなる。
//
// ------------------------------------------------------------
// Num は再帰の終点
// ------------------------------------------------------------
// Calculation の value() は左右にも value() を聞きに行くが、
// Num に着いたら自分の数を返して止まる。これで再帰が無限に続かない。
//
// 名前を Number にしていないのは、java.lang.Number が既にあるため。
// ============================================================

// record: 値を持つだけの型を短く書くための書き方（Java 16以降）
//         フィールド・コンストラクタ・取り出し用メソッド（number()）を自動で作る
public record Num(int number) implements Expression {

    // 数そのものが答え。3 の答えは 3
    public int value() {
        return number;
    }

    // 数を文字にする。3 → "3"
    // String.valueOf は int を String にする標準の関数
    public String text() {
        return String.valueOf(number);
    }

    // 数はいつでも計算できるので常に true
    public boolean isComputable() {
        return true;
    }

    // 0以上の数はそれ以上ばらせないので、かっこは絶対に要らない（一番強い 3 を返す）。
    // マイナスの数は前に「-」が付いているので、演算子の隣に置くとくっついて見える。
    //   5 + -3   読みにくい
    //   5 + (-3) こう出したい
    // 一番弱い 0 を返すことで、どの演算子の下でもかっこが付くようにしている。
    public int precedence() {
        return number < 0 ? 0 : 3;
    }
}
