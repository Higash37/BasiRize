package com.basirize;

// ============================================================
// このファイルの目的
// ============================================================
// 「3 + 7」のような計算式を、1つのオブジェクトとして持つ。
//
// 持つものは3つ。
//   左の式   3
//   演算子   +
//   右の式   7
//
// ============================================================
// なぜ1つのオブジェクトにまとめるのか
// ============================================================
// 理由1：入れ子にできるようにするため
//
//   バラバラの変数で持つと、こうなる。
//       int left = 3;
//       Operator op = Operator.ADD;
//       int right = 7;
//
//   ここで (3 + 7) × 2 を作りたいとする。左側に「3 + 7」を入れたい。
//   しかし int には「3 + 7 という組」を入れられないので詰む。
//
//   1つのオブジェクトにまとめておけば、その中にまた同じものを入れられる。
//       Calculation( Calculation(3, +, 7), ×, 2 )
//
//   この入れ子が「木構造」になる。項が増えても同じ仕組みで表せる。
//
// 理由2：問題文と答えがズレないようにするため
//
//   同じオブジェクトから問題文と答えの両方を取り出すので、必ず対応する。
//   別々のリストで管理すると、片方だけ修正して食い違っても検知できない。
//
// ============================================================
// なぜ「数値の配列 + 演算子の配列」ではダメだったのか
// ============================================================
//   numbers = [3, 7, 2]
//   ops     = ["+", "×"]
//
// この持ち方は「並び」しか表せない。
// 「3 + 7 × 2」を左から順に計算すると 20 になるが、数学的な正解は 17。
// かっこの位置も、演算子の優先順位も、書く場所がない。
//
// 木なら、形そのものが計算の順番を表す。
//
//       +                      ×
//      / \                    / \
//     3   ×                  +   2
//        / \                / \
//       7   2              3   7
//
//     3 + (7 × 2) = 17    (3 + 7) × 2 = 20
//
// かっこは、この形を1行の文字列に書き出すための記号にすぎない。
//
// ============================================================
// 参考にした考え方
// ============================================================
// ・抽象構文木（AST / Abstract Syntax Tree）
//     式や文を木で表すデータ構造。プログラミング言語のコンパイラが必ず作る。
//     電卓アプリ、Excelの数式、SQLの条件式なども同じ形で扱われる。
//     自己流ではなく、式を扱うときの標準的なやり方。
//
// ・再帰（recursion）
//     木をたどる処理は、自分の中で自分を呼ぶ形になる。
//     Calculation の中で左と右にも同じことを聞き、葉（Num）に着いたら止まる。
//
// ・共通の型でまとめる（Expression インターフェース）
//     左右には Num が来ることも Calculation が来ることもある。
//     「どちらでもよい」と書ける名前が必要なので Expression を用意した。
//     これがないと、木が自分自身を含められない。

// record: 値をまとめて持つだけの型を短く書くための書き方（Java 16以降）
//         フィールド・コンストラクタ・取り出し用メソッドを自動で作ってくれる
// (Expression left, Operator operator, Expression right): 持つもの3つ
//         left と right が Expression 型なので、Num でも Calculation でも入る
record Calculation(Expression left, Operator operator, Expression right) implements Expression {

    // 答えを出す。
    // 左と右にそれぞれ「あなたの答えは？」と聞き、返ってきた2つを演算子に計算させる。
    //
    // 左が Num なら数がそのまま返って終わり。
    // 左が Calculation なら、その中でまた同じことが起きる（再帰）。
    // 木がどれだけ深くても、一番上で1回呼べば全部計算される。
    public int value() {
        return operator.apply(left.value(), right.value());
    }

    // 問題文用の文字列を作る。
    // 左を文字にして、記号を挟んで、右を文字にする。かっこは必要なときだけ付ける。
    //
    // 以前は常にかっこで包んでいたので (3 + 5) = ? のように余計なかっこが出ていた。
    // プリントとして使えないので、優先順位を見て必要最小限だけ付けるようにしている。
    public String text() {
        return render(left, false) + " " + operator.symbol() + " " + render(right, true);
    }

    // 子の式を文字にする。かっこが必要ならかっこで囲む。
    //
    // かっこが要るのは「かっこを外すと意味が変わってしまう」ときだけ。
    // 判断は2つ。
    //
    // ① 子の方が弱いとき
    //      (3 + 5) × 2    +（弱）が ×（強）の下にいる → 外すと 3 + 5 × 2 になり別の式
    //      3 + 5 × 2      ×（強）が +（弱）の下にいる → 外しても同じなので不要
    //
    // ② 同じ強さで、親が - や ÷ で、子が右側にいるとき
    //      8 - (3 - 1)    外すと 8 - 3 - 1 になり別の式
    //      8 + (3 - 1)    外して 8 + 3 - 1 でも同じなので不要
    //      12 ÷ (3 × 2)   外すと 12 ÷ 3 × 2 になり別の式
    //
    // isRight は「この子が右側にいるか」。左側なら②は起きない。
    private String render(Expression child, boolean isRight) {
        boolean needsBrackets = child.precedence() < operator.precedence();

        if (isRight
                && child.precedence() == operator.precedence()
                && !operator.keepsMeaningOnRight()) {
            needsBrackets = true;
        }

        return needsBrackets ? "(" + child.text() + ")" : child.text();
    }

    // この式が計算できるかを調べる。
    //
    // 整数の割り算には2つの落とし穴がある。
    //   1. 0 で割ると実行時に ArithmeticException で落ちる
    //   2. 割り切れないと小数が切り捨てられる（7 ÷ 3 が 2 になる）
    //
    // 数の範囲を 1〜10 にしても防げない。部分式の値が 0 になりうるため。
    //   (2 ÷ 10) → 0    整数割り算で切り捨てられた
    //   (3 - 3)  → 0    引き算でゼロになった
    public boolean isComputable() {
        // 先に左右を調べる。順番が重要。
        // 逆にすると、下の right.value() を呼んだ時点で / by zero が起きて、
        // 検査している最中に落ちてしまう。
        if (!left.isComputable() || !right.isComputable()) {
            return false;
        }
        // ここまで来れば左右は安全に value() を呼べる
        if (operator == Operator.DIVIDE) {
            int r = right.value();
            // 0 で割れない
            if (r == 0) {
                return false;
            }
            // % は割った余り。余りが 0 でない ＝ 割り切れない
            if (left.value() % r != 0) {
                return false;
            }
        }
        return true;
    }

    // 表示上の優先順位は、自分の演算子の優先順位そのもの。
    // 3 × 5 は 2、3 + 5 は 1。
    public int precedence() {
        return operator.precedence();
    }
}