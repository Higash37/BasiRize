package com.basirize;

// ============================================================
// 式（Expression）
// ============================================================
// 「3」も「3 + 7」も、数学ではどちらも「式」と呼ぶ。
// このインターフェースは、その2つをまとめて指すための名前。
//
//   Expression
//     ├ Num          数        3
//     └ Calculation  計算      3 + 7
//
// ------------------------------------------------------------
// なぜ必要か
// ------------------------------------------------------------
// Calculation の左右には、Num が来ることも Calculation が来ることもある。
//
//   3 + 7           Num         + Num
//   (3 + 7) × 2     Calculation × Num
//   1 + 2 × 3       Num         + Calculation
//   (1+2) × (3+4)   Calculation × Calculation
//
// Java は型を1つに決めないと書けないので、「Num か Calculation のどちらか」を
// 意味する名前がないと、この4通りを1つの型で表せない。
// その名前がこの Expression。これがないと木が自分自身を含められない。
//
// ------------------------------------------------------------
// このファイルには動くコードが1行もない
// ------------------------------------------------------------
// interface は「これができる」という約束を決めるだけ。実際の中身は
// implements した側（Num / Calculation）がそれぞれ書く。
// 書き忘れるとコンパイルエラーになるので、約束が守られているかを Java が保証する。
//
// 呼ぶ側は、中身が Num なのか Calculation なのかを知らなくてよい。
// Expression として受け取り、下の3つを呼ぶだけで済む。
// ============================================================
interface Expression {

    // 計算した答えを返す。問題の「答え」を作るときに使う
    int value();

    // 表示用の文字列を返す。問題文を作るときに使う
    String text();

    // この式が計算できるかを返す。
    // 0で割っていないか、割り算が割り切れるかを確認する。
    // value() を呼ぶ前にこれで確認しないと、実行時に / by zero で落ちる
    boolean isComputable();

    // 表示するときの優先順位。大きいほど強く結びついている。
    //
    //   3          → 3（それ以上ばらせない。かっこは要らない）
    //   3 × 5      → 2
    //   3 + 5      → 1
    //   -3         → 0（マイナスの数は前に付く記号があるので、かっこで囲む）
    //
    // 親の演算子より弱ければ、文字にするときかっこで囲む必要がある。
    // 計算には使わない。問題文の見た目を決めるためだけのもの。
    int precedence();
}
